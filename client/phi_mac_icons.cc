std::vector<unsigned char> PhiTintedIconBgra(const PhiMacIcon& icon,
                                             COLORREF color,
                                             int out_size) {
  if (out_size <= 0) {
    out_size = icon.width;
  }
  // Area-average the mask down to the destination pixel size so the GDI
  // blend never has to filter.
  std::vector<double> mask(static_cast<size_t>(out_size) * out_size, 0.0);
  const double step_x = static_cast<double>(icon.width) / out_size;
  const double step_y = static_cast<double>(icon.height) / out_size;
  for (int y = 0; y < out_size; ++y) {
    const int sy0 = static_cast<int>(y * step_y);
    const int sy1 = std::min(icon.height,
                             std::max(sy0 + 1, static_cast<int>((y + 1) * step_y)));
    for (int x = 0; x < out_size; ++x) {
      const int sx0 = static_cast<int>(x * step_x);
      const int sx1 = std::min(
          icon.width, std::max(sx0 + 1, static_cast<int>((x + 1) * step_x)));
      double sum = 0.0;
      for (int sy = sy0; sy < sy1; ++sy) {
        for (int sx = sx0; sx < sx1; ++sx) {
          // SAFETY: `alpha` is a width*height array by construction above,
          // and sx/sy are clamped to it.
          sum += UNSAFE_BUFFERS(icon.alpha[sy * icon.width + sx]);
        }
      }
      mask[static_cast<size_t>(y) * out_size + x] =
          sum / ((sy1 - sy0) * (sx1 - sx0));
    }
  }
  std::vector<unsigned char> bgra(static_cast<size_t>(out_size) * out_size *
                                  4);
  const unsigned r = GetRValue(color);
  const unsigned g = GetGValue(color);
  const unsigned b = GetBValue(color);
  for (size_t i = 0; i < mask.size(); ++i) {
    const unsigned a =
        static_cast<unsigned>(std::min(255.0, mask[i] + 0.5));
    const size_t at = i * 4;
    bgra[at] = static_cast<unsigned char>(b * a / 255);
    bgra[at + 1] = static_cast<unsigned char>(g * a / 255);
    bgra[at + 2] = static_cast<unsigned char>(r * a / 255);
    bgra[at + 3] = static_cast<unsigned char>(a);
  }
  return bgra;
}

