"""Copies the framework's public contract into client/compat.

These files come from the private framework tree and are what a client build
compiles against, so they are committed here. Run it from a framework checkout
whenever they change; --check fails if the copies have drifted.

  sync-framework-headers.py --src <chromium-src> [--check]
"""

import argparse
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
COMPAT = os.path.join(REPO, "client", "compat")
COPIED = (
    "chrome/browser/phinomenon/phi_framework/phi_framework_api.h",
    "chrome/browser/phinomenon/phi_framework/phi_ids.h",
    "chrome/browser/phinomenon/phi_framework/phi_window_snapshot.h",
    "ui/base/win/phi_hosted_window.h",
)
COMMAND_IDS = "chrome/app/chrome_command_ids.h"


def command_ids(src):
    """Only the commands the client names, with the framework's values."""
    text = open(os.path.join(src, COMMAND_IDS), encoding="utf-8").read()
    values = dict(re.findall(r"^#define\s+(IDC_\w+)\s+(\S+)", text, re.M))
    used = set()
    client = os.path.join(REPO, "client")
    for name in os.listdir(client):
        if name.endswith((".cc", ".h")):
            with open(os.path.join(client, name), encoding="utf-8") as f:
                used |= set(re.findall(r"\bIDC_[A-Z0-9_]+\b", f.read()))
    used &= set(values)  # IDC_ARROW and friends are the system's.
    lines = ["// Generated by tools/sync-framework-headers.py: the framework's "
             "values for",
             "// the commands the client uses.",
             "#ifndef CHROME_APP_CHROME_COMMAND_IDS_H_",
             "#define CHROME_APP_CHROME_COMMAND_IDS_H_", ""]
    lines += [f"#define {name} {values[name]}" for name in sorted(used)]
    lines += ["", "#endif  // CHROME_APP_CHROME_COMMAND_IDS_H_", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--src", required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    wanted = {path: open(os.path.join(args.src, path), encoding="utf-8").read()
              for path in COPIED}
    wanted[COMMAND_IDS] = command_ids(args.src)
    drift = []
    for path, text in wanted.items():
        target = os.path.join(COMPAT, path)
        if args.check:
            if (not os.path.exists(target) or
                    open(target, encoding="utf-8").read() != text):
                drift.append(path)
            continue
        os.makedirs(os.path.dirname(target), exist_ok=True)
        with open(target, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    if drift:
        sys.exit("framework headers differ from client/compat: " +
                 ", ".join(drift) + " (run tools/sync-framework-headers.py)")
    print("ok: framework headers")


if __name__ == "__main__":
    main()
