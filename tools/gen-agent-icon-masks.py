#!/usr/bin/env python3
"""Pack the Mac's agent brand marks into a client mask table.

The Mac ships the marks of the code agents that can drive Phi (Claude Code,
Codex, Cursor, …) as template imagesets under Assets ▸ agents: the alpha is
the shape, the colour is ignored, and every glyph's ink is normalized to 42
of the 54px canvas so the brands read as one size (AgentDriverBadge.
assetInkRatio). The Windows client tints them at draw time exactly as
phi_icon_masks.cc does for the Phi icon catalog.

Output is phibrowser-win/client/phi_agent_icon_masks.cc: the @3x rendition's
54x54 alpha plane, run-length packed as (count, value) byte pairs, the same
format the catalog masks use so PhiTintedIconBgra can consume it unchanged.

    python3 tools/gen-agent-icon-masks.py [--mac /path/to/phibrowser-mac]

Needs Pillow for the PNG decode.
"""

import argparse
import os
import sys

try:
    from PIL import Image
except ImportError:  # pragma: no cover
    sys.exit('gen-agent-icon-masks.py needs Pillow: pip install pillow')

MASK = 54  # The @3x canvas, px square.

# Client ids -> the Mac imageset names (DeveloperSettingsView.swift's
# skillTargets and AgentDriverBadge's assets). "generic" is the terminal
# glyph an unbranded agent wears; "phi" the browser's own mark.
ICONS = [
    ('claude', 'agent-claude'),
    ('openai', 'agent-openai'),
    ('cursor', 'agent-cursor'),
    ('hermes', 'agent-hermes'),
    ('openclaw', 'agent-openclaw'),
    ('pi', 'agent-pi'),
    ('grok', 'agent-grok'),
    ('grokbot', 'agent-grokbot'),
    ('antigravity', 'agent-antigravity'),
    ('copilot', 'agent-copilot'),
    ('opencode', 'agent-opencode'),
    ('qwen', 'agent-qwen'),
    ('codebuddy', 'agent-codebuddy'),
    ('generic', 'agent-generic'),
    ('phi', 'agent-phi'),
]


def alpha_plane(path):
    image = Image.open(path).convert('RGBA')
    if image.size != (MASK, MASK):
        sys.exit(f'{path}: {image.size[0]}x{image.size[1]}, expected '
                 f'{MASK}x{MASK}')
    return bytearray(image.getchannel('A').tobytes())


def rle(mask):
    out = []
    i = 0
    while i < len(mask):
        v = mask[i]
        run = 1
        while i + run < len(mask) and mask[i + run] == v and run < 255:
            run += 1
        out.append((run, v))
        i += run
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--mac', default=os.path.expanduser('~/Phi/phibrowser-mac'))
    ap.add_argument('--out', default=os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        'client', 'phi_agent_icon_masks.cc'))
    args = ap.parse_args()

    root = os.path.join(args.mac, 'Resources', 'Assets.xcassets', 'agents')
    blob, entries = [], []
    for icon_id, asset in ICONS:
        png = os.path.join(root, f'{asset}.imageset', f'{asset}@3x.png')
        if not os.path.exists(png):
            sys.exit(f'missing {png}')
        pairs = rle(alpha_plane(png))
        offset = len(blob)
        for run, value in pairs:
            blob.append(run)
            blob.append(value)
        entries.append((icon_id, offset, len(pairs) * 2))
        print(f'{icon_id:12} {len(pairs) * 2:6} bytes', file=sys.stderr)

    with open(args.out, 'w') as f:
        f.write('''// Copyright 2026 Phinomenon Inc.
// Licensed under the Apache License, Version 2.0; see the LICENSE file.

// GENERATED by tools/gen-agent-icon-masks.py from the Mac's agent brand
// imagesets (Resources/Assets.xcassets/agents, the @3x renditions — template
// images whose alpha is the shape). 54x54 alpha masks, run-length packed as
// (count, value) byte pairs. Do not edit by hand.

#include "phibrowser-win/client/phi_agent_icons.h"

#include <map>
#include <string>
#include <vector>

#include "base/containers/span.h"
#include "base/no_destructor.h"

namespace phi_client {

namespace {

constexpr int kMaskSize = 54;

constexpr unsigned char kMaskRle[] = {
''')
        line = '    '
        for b in blob:
            piece = f'{b},'
            if len(line) + len(piece) > 76:
                f.write(line.rstrip() + '\n')
                line = '    '
            line += piece + ' '
        if line.strip():
            f.write(line.rstrip() + '\n')
        f.write('''};

struct MaskEntry {
  const char* id;
  unsigned int offset;
  unsigned int length;
};

constexpr MaskEntry kMaskEntries[] = {
''')
        for icon_id, offset, length in entries:
            f.write(f'    {{"{icon_id}", {offset}, {length}}},\n')
        f.write('''};

}  // namespace

const PhiMacIcon* PhiAgentIconMask(const std::string& id) {
  // Decoded once; map nodes never move, so the PhiMacIcon views handed out
  // stay valid for the process lifetime.
  struct Tables {
    std::map<std::string, std::vector<unsigned char>> data;
    std::map<std::string, PhiMacIcon> icons;
  };
  static const base::NoDestructor<Tables> tables([] {
    const base::span<const unsigned char> rle(kMaskRle);
    Tables t;
    for (const MaskEntry& entry : kMaskEntries) {
      std::vector<unsigned char> mask;
      mask.reserve(kMaskSize * kMaskSize);
      for (unsigned int i = 0; i + 1 < entry.length; i += 2) {
        const unsigned char run = rle[entry.offset + i];
        const unsigned char value = rle[entry.offset + i + 1];
        mask.insert(mask.end(), run, value);
      }
      t.data[entry.id] = std::move(mask);
    }
    for (const auto& [icon_id, mask] : t.data) {
      t.icons[icon_id] = {kMaskSize, kMaskSize, mask.data()};
    }
    return t;
  }());
  auto it = tables->icons.find(id);
  return it == tables->icons.end() ? nullptr : &it->second;
}

}  // namespace phi_client
''')


if __name__ == '__main__':
    main()
