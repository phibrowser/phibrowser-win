"""Rasterize the Mac native new-tab page artwork into client mask tables.

The Mac's NewTabViewController shows two template images: the Phi mark
(native-NTP-icon.imageset) and the incognito hat-and-glasses
(native-NTP-incognito.imageset), each as a 58pt PDF with a light and a dark
variant. Both variants are the SAME shape in black and in #F8F8F8, so the
client ports the shape once as an alpha mask and tints it at draw time,
exactly as phi_mac_icons.cc does for the sidebar's template icons.

Output is phibrowser-win/client/phi_ntp_art.cc: 192x192 alpha masks (the
Mac shows them at 64pt, so 192 covers 300% scaling before PhiTintedIconBgra
has to upscale), run-length packed as (count, value) byte pairs.

    python3 tools/gen-ntp-art.py [--mac /path/to/phibrowser-mac]

Needs pdftocairo (poppler) and Pillow.
"""

import argparse
import os
import subprocess
import sys
import tempfile

from PIL import Image

MASK = 192

ART = [
    # (accessor, imageset, light-variant file)
    ("PhiNativeNtpLogo", "native-NTP-icon.imageset", "Frame 5.pdf"),
    ("PhiNativeNtpIncognito", "native-NTP-incognito.imageset", "Frame 5.pdf"),
]


def rasterize(pdf, out_dir):
    base = os.path.join(out_dir, "art")
    subprocess.run(
        ["pdftocairo", "-png", "-transp", "-scale-to", str(MASK),
         "-singlefile", pdf, base],
        check=True)
    image = Image.open(base + ".png").convert("RGBA")
    if image.size != (MASK, MASK):
        canvas = Image.new("RGBA", (MASK, MASK), (0, 0, 0, 0))
        canvas.paste(image, ((MASK - image.width) // 2,
                             (MASK - image.height) // 2))
        image = canvas
    return bytes(image.getchannel("A").getdata())


def rle(mask):
    out = bytearray()
    i = 0
    while i < len(mask):
        value = mask[i]
        run = 1
        while i + run < len(mask) and mask[i + run] == value and run < 255:
            run += 1
        out += bytes((run, value))
        i += run
    return bytes(out)


def main():
    parser = argparse.ArgumentParser()
    repo = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    parser.add_argument("--mac", default=os.path.join(
        os.path.dirname(repo), "phibrowser-mac"))
    parser.add_argument("--out", default=os.path.join(
        repo, "client", "phi_ntp_art.cc"))
    args = parser.parse_args()

    assets = os.path.join(args.mac, "Resources", "Assets.xcassets")
    tables = []
    with tempfile.TemporaryDirectory() as tmp:
        for accessor, imageset, filename in ART:
            pdf = os.path.join(assets, imageset, filename)
            if not os.path.exists(pdf):
                sys.exit(f"missing Mac asset: {pdf}")
            tables.append((accessor, imageset, rle(rasterize(pdf, tmp))))

    with open(args.out, "w", encoding="utf-8") as f:
        f.write('''// Copyright 2026 Phinomenon Inc.
// Licensed under the Apache License, Version 2.0; see the LICENSE file.

// GENERATED by tools/gen-ntp-art.py from the Mac's native new-tab page
// imagesets — do not edit by hand.

#include <vector>

#include "base/containers/span.h"
#include "base/no_destructor.h"
#include "phibrowser-win/client/phi_mac_icons.h"

namespace phi_client {

namespace {

constexpr int kArtSize = %d;

// (run, value) pairs of a %dx%d alpha mask.
''' % (MASK, MASK, MASK))
        for accessor, imageset, blob in tables:
            f.write(f"// {imageset}\n")
            f.write(f"constexpr unsigned char k{accessor}Rle[] = {{\n")
            line = "    "
            for b in blob:
                piece = f"{b},"
                if len(line) + len(piece) > 76:
                    f.write(line.rstrip() + "\n")
                    line = "    "
                line += piece + " "
            if line.strip():
                f.write(line.rstrip() + "\n")
            f.write("};\n\n")
        f.write('''std::vector<unsigned char> Decode(base::span<const unsigned char> rle) {
  std::vector<unsigned char> mask;
  mask.reserve(static_cast<size_t>(kArtSize) * kArtSize);
  for (size_t i = 0; i + 1 < rle.size(); i += 2) {
    mask.insert(mask.end(), rle[i], rle[i + 1]);
  }
  mask.resize(static_cast<size_t>(kArtSize) * kArtSize, 0);
  return mask;
}

}  // namespace

''')
        for accessor, imageset, blob in tables:
            f.write(f'''const PhiMacIcon& {accessor}() {{
  static const base::NoDestructor<std::vector<unsigned char>> mask(
      Decode(base::span<const unsigned char>(k{accessor}Rle)));
  static const PhiMacIcon icon = {{kArtSize, kArtSize, mask->data()}};
  return icon;
}}

''')
        f.write("}  // namespace phi_client\n")
    total = sum(len(blob) for _, _, blob in tables)
    print(f"wrote {args.out} ({total} rle bytes)", file=sys.stderr)


if __name__ == "__main__":
    main()
